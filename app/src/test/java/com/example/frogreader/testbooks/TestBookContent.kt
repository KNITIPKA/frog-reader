package com.example.frogreader.testbooks

/**
 * The comparison book, written once for all four formats.
 *
 * Every check is numbered, and the numbering is identical in every file — so
 * "тест 63 в EPUB рисует таблицу, а в MOBI6 нет" is a statement about the
 * engine. Where a format cannot express a check at all it gets a visible stub
 * ([Block.Test.formats]); where it *can* carry the markup but is known to
 * treat it differently it gets its own expectation line
 * ([Block.Test.expectedPerFormat]), so a known limitation never reads as a
 * fresh bug.
 */
object TestBookContent {

