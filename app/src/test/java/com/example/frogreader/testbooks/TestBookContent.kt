            "не обрубилось посередине, а внизу и наверху оставалось не меньше двух строк. "

    /**
     * Filler by whole sentences, never by character count: a paragraph that
     * ends mid-word would look exactly like the bug several checks are
     * watching for.
     */
    private fun filler(sentences: Int): String = SENTENCE.repeat(sentences).trim()

